import { mkdir, rename, rm } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';

export async function writeChanged(
  file: string,
  content: string,
): Promise<void> {
  const target = Bun.file(file);
  if ((await target.exists()) && (await target.text()) === content) return;
  await mkdir(dirname(file), { recursive: true });
  const temporary = `${file}.${crypto.randomUUID()}.tmp`;
  try {
    await Bun.write(temporary, content);
    await rename(temporary, file);
  } finally {
    await rm(temporary, { force: true });
  }
}

export async function exportCatalogue(
  data: Record<string, unknown>,
  output: string,
  options: { types: boolean; split: boolean },
): Promise<void> {
  const files = new Map<string, string>();
  const add = (file: string, value: unknown) => {
    const json = JSON.stringify(value, null, 2);
    if (json === undefined) throw new Error(`Cannot serialize ${file}`);
    files.set(file, `${json}\n`);
    if (options.types)
      files.set(
        file.replace(/\.json$/, '.d.json.ts'),
        `// Generated by @teyfix/directory-loader.\ndeclare const messages: ${json};\nexport default messages;\n`,
      );
  };
  if (options.split) {
    for (const [name, value] of Object.entries(data)) {
      if (!/^[\w-]+$/.test(name))
        throw new Error(`Unsafe output name: ${name}`);
      add(join(output, `${name}.json`), value);
    }
  } else {
    if (!output.endsWith('.json'))
      throw new Error('Output must end in .json; use split() for a directory');
    add(output, data);
  }
  // Serialize the complete result before publishing any file.
  const directory = options.split ? output : dirname(output);
  const manifest = join(
    directory,
    options.split
      ? '.directory-loader.outputs.json'
      : `.${basename(output)}.outputs.json`,
  );
  const previous: unknown = (await Bun.file(manifest).exists())
    ? await Bun.file(manifest).json()
    : [];
  if (
    !Array.isArray(previous) ||
    previous.some(
      (name: unknown) =>
        typeof name !== 'string' ||
        basename(name) !== name ||
        !/\.(json|d\.json\.ts)$/.test(name),
    )
  )
    throw new Error(`Invalid output manifest: ${manifest}`);
  for (const [file, content] of files) await writeChanged(file, content);
  const current = [...files.keys()].map((file) => basename(file));
  for (const file of previous)
    if (!current.includes(file))
      await rm(join(directory, file), { force: true });
  await writeChanged(manifest, `${JSON.stringify(current, null, 2)}\n`);
}
